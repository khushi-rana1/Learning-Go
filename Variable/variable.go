package main

import "fmt"

func main() {

   //declare multiple variables on the same line
   var a, b, c, d int = 1, 2, 3, 4
   fmt.Println(a, b, c, d)

   //declare a variable using the var keyword
   var name string = "Momo"
   fmt.Println(name)

   ////declare a variable using := sign
   x := 10
   fmt.Println(x)

}
